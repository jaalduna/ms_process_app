import zlib from "zlib"

/**
 * Build a minimal but *valid* ZIP archive (stored / no compression) entirely in
 * memory, with no external dependencies. Used by mock download endpoints that
 * the frontend consumes as `application/zip` blobs.
 *
 * @param {string[]} entryNames - file names to include (e.g. ["weights.csv"])
 * @param {string} [note] - free text dropped into a README.txt manifest entry
 * @returns {Buffer} the complete .zip bytes
 */
export function buildMockZip(entryNames = [], note = "") {
  const files = []

  // Always include a manifest so an empty tag still yields a non-empty archive.
  files.push({
    name: "README.txt",
    data: Buffer.from(
      `Mock archive generated by ms_process_app mock-server.\n${note}\nEntries: ${entryNames.join(", ") || "(none)"}\n`,
      "utf8",
    ),
  })

  for (const name of entryNames) {
    files.push({
      name,
      data: Buffer.from(`# mock content for ${name}\nid,value\n1,mock\n2,mock\n`, "utf8"),
    })
  }

  const localParts = []
  const centralParts = []
  let offset = 0

  for (const f of files) {
    const nameBuf = Buffer.from(f.name, "utf8")
    const crc = zlib.crc32 ? zlib.crc32(f.data) : crc32(f.data)
    const size = f.data.length

    // Local file header
    const local = Buffer.alloc(30)
    local.writeUInt32LE(0x04034b50, 0) // signature
    local.writeUInt16LE(20, 4) // version needed
    local.writeUInt16LE(0, 6) // flags
    local.writeUInt16LE(0, 8) // compression method = stored
    local.writeUInt16LE(0, 10) // mod time
    local.writeUInt16LE(0, 12) // mod date
    local.writeUInt32LE(crc >>> 0, 14)
    local.writeUInt32LE(size, 18) // compressed size
    local.writeUInt32LE(size, 22) // uncompressed size
    local.writeUInt16LE(nameBuf.length, 26)
    local.writeUInt16LE(0, 28) // extra length
    localParts.push(local, nameBuf, f.data)

    // Central directory header
    const central = Buffer.alloc(46)
    central.writeUInt32LE(0x02014b50, 0)
    central.writeUInt16LE(20, 4) // version made by
    central.writeUInt16LE(20, 6) // version needed
    central.writeUInt16LE(0, 8) // flags
    central.writeUInt16LE(0, 10) // compression
    central.writeUInt16LE(0, 12)
    central.writeUInt16LE(0, 14)
    central.writeUInt32LE(crc >>> 0, 16)
    central.writeUInt32LE(size, 20)
    central.writeUInt32LE(size, 24)
    central.writeUInt16LE(nameBuf.length, 28)
    central.writeUInt16LE(0, 30) // extra
    central.writeUInt16LE(0, 32) // comment
    central.writeUInt16LE(0, 34) // disk number
    central.writeUInt16LE(0, 36) // internal attrs
    central.writeUInt32LE(0, 38) // external attrs
    central.writeUInt32LE(offset, 42) // local header offset
    centralParts.push(central, nameBuf)

    offset += local.length + nameBuf.length + f.data.length
  }

  const centralBuf = Buffer.concat(centralParts)
  const localBuf = Buffer.concat(localParts)

  // End of central directory record
  const eocd = Buffer.alloc(22)
  eocd.writeUInt32LE(0x06054b50, 0)
  eocd.writeUInt16LE(0, 4) // disk
  eocd.writeUInt16LE(0, 6) // disk with central dir
  eocd.writeUInt16LE(files.length, 8) // entries on this disk
  eocd.writeUInt16LE(files.length, 10) // total entries
  eocd.writeUInt32LE(centralBuf.length, 12) // central dir size
  eocd.writeUInt32LE(localBuf.length, 16) // central dir offset
  eocd.writeUInt16LE(0, 20) // comment length

  return Buffer.concat([localBuf, centralBuf, eocd])
}

/** Fallback CRC-32 for Node versions without zlib.crc32. */
function crc32(buf) {
  let crc = ~0
  for (let i = 0; i < buf.length; i++) {
    crc ^= buf[i]
    for (let j = 0; j < 8; j++) {
      crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1))
    }
  }
  return ~crc >>> 0
}
